def kind_for(index: int) -> tuple[str, str | None]:
    if index == 0:
        return "core", None
    if index <= 3:
        return "variant", "lexical"
    if index <= 9:
        return "real", "context"
    return "personal", "personal"


def ruby_rows(sentence_id: str, text: str) -> list[tuple]:
    rows = []
    for position, token in enumerate(TOKENIZER.tokenize(text, MODE)):
        surface = token.surface()
        token_reading = hira(token.reading_form()) if token.reading_form() != "*" else surface
        rows.append((sentence_id, position, surface, token_reading if KANJI_RE.search(surface) else None))
    return rows


def chunk_rows(sentence_id: str, text: str, translation: str) -> list[tuple]:
    jp_parts = [part for part in text.split("、", 1) if part]
    zh_parts = [part for part in translation.split("，", 1) if part]
    if len(jp_parts) != len(zh_parts):
        jp_parts, zh_parts = [text], [translation]
    rows = []
    for position, (jp, zh) in enumerate(zip(jp_parts, zh_parts)):
        rows.append((sentence_id, position, jp, reading(jp), zh, "前提或修饰部分" if position == 0 and len(jp_parts) > 1 else "主要陈述"))
    return rows


def main() -> None:
    backup = DATABASE.with_name(f"{DATABASE.stem}.before-n1-{datetime.now():%Y%m%d-%H%M%S}{DATABASE.suffix}")
    shutil.copy2(DATABASE, backup)
    print(f"Backup: {backup}")
    with sqlite3.connect(DATABASE) as connection:
        connection.execute("PRAGMA foreign_keys=ON")
        connection.execute("DELETE FROM sentences WHERE id LIKE 'n1\\_%' ESCAPE '\\'")
        connection.execute("DELETE FROM grammar_points WHERE id LIKE 'n1\\_%' ESCAPE '\\'")
        for family_index, family in enumerate(FAMILIES, 1):
            grammar_id = f"n1_{family_index:02d}_{family.key}"
            connection.execute(
                "INSERT INTO grammar_points VALUES (?,?,?,?,?,?,?,?,?,?)",
                (grammar_id, "N1", family.title, family.pattern, family.meaning, family.formation, family.rationale, family.nuance, family.mistakes, "draft"),
            )
            core_id = f"n1_{family_index:02d}_core"
            for example_index, (text, translation) in enumerate(family.examples):
                kind, variant_type = kind_for(example_index)
                sentence_id = core_id if kind == "core" else f"n1_{family_index:02d}_{kind}_{example_index:02d}"
                parent_id = None if kind == "core" else core_id
                connection.execute(
                    """INSERT INTO sentences
                       (id,level_code,kind,parent_sentence_id,variant_type,text,reading,translation_zh,scene_zh,register,
                        grammar_note_zh,audio_text,source_type,source_ref,copyright_status,status)
                       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                    (sentence_id, "N1", kind, parent_id, variant_type, text, reading(text), translation,
                     f"在正式或书面场景中理解并表达：{translation}", "formal",
                     f"本句使用「{family.pattern}」。{family.meaning} 当前句通过这个结构组织前后信息。",
                     text, "original", "N1原创补充课程", "original", "draft"),
                )
                connection.execute("INSERT INTO sentence_grammar VALUES (?,?,?)", (sentence_id, grammar_id, "new" if kind == "core" else "review"))
                connection.executemany(
                    "INSERT INTO sentence_ruby_segments(sentence_id,position,surface,reading) VALUES (?,?,?,?)",
                    ruby_rows(sentence_id, text),
                )
                connection.executemany(
                    "INSERT INTO sentence_chunks(sentence_id,position,surface,reading,meaning_zh,function_zh) VALUES (?,?,?,?,?,?)",
                    chunk_rows(sentence_id, text, translation),
                )
        tokens, linked = index_course_sentences(connection)
        counts = dict(connection.execute("SELECT kind,COUNT(*) FROM sentences GROUP BY kind"))
        total = connection.execute("SELECT COUNT(*) FROM sentences").fetchone()[0]
        n1 = connection.execute("SELECT COUNT(*) FROM sentences WHERE level_code='N1'").fetchone()[0]
        integrity = connection.execute("PRAGMA integrity_check").fetchone()[0]
        if total != 6120 or n1 != 120 or integrity != "ok":
            raise RuntimeError(f"N1 safety check failed: total={total}, n1={n1}, integrity={integrity}")
        connection.commit()
    print(json.dumps({"total_course": total, "N1": n1, "kinds": counts, "tokens": tokens, "linked_tokens": linked, "integrity": integrity}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
